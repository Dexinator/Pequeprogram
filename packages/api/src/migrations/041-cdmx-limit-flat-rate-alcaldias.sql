-- Mover fuera de la zona CDMX ($95 plano) todo CP que no sea de las 5 alcaldías cubiertas
UPDATE shipping_zone_postcodes
SET zone_id = (SELECT id FROM shipping_zones WHERE zone_code = 'nacional')
WHERE zone_id = (SELECT id FROM shipping_zones WHERE zone_code = 'cdmx')
  AND postal_code NOT IN (SELECT postal_code FROM cdmx_flat_rate_cps);

-- Asegurar que los CPs de las 5 alcaldías estén en la zona CDMX (por si alguno quedó fuera)
UPDATE shipping_zone_postcodes
SET zone_id = (SELECT id FROM shipping_zones WHERE zone_code = 'cdmx')
WHERE postal_code IN (SELECT postal_code FROM cdmx_flat_rate_cps)
  AND zone_id <> (SELECT id FROM shipping_zones WHERE zone_code = 'cdmx');

